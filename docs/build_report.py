def split_sections(md: str) -> dict:
    """Split a generated Markdown report into {'intro': lines, '2. Missing values ...': lines, ...}."""
    sections, current = {"intro": []}, "intro"
    for line in md.splitlines():
        if line.startswith("## "):
            current = line[3:].strip()
            sections[current] = []
        else:
            sections[current].append(line)
    return sections


def table_from_lines(lines: list) -> tuple:
    block = [ln for ln in lines if ln.startswith("|") and not re.match(r"^\|[\s\-:|]+\|$", ln)]
    rows = [[c.strip().replace("\x00", "|") for c in r.replace("\\|", "\x00").strip().strip("|").split("|")] for r in block]
    return (rows[0], rows[1:]) if rows else ([], [])


def find_section(sections: dict, start: str) -> list:
    return next((v for k, v in sections.items() if k.startswith(start)), [])


def compact_quality(doc, md: str) -> None:
    """A one-and-a-half page version of the data-quality report."""
    sec = split_sections(md)
    summary = next((ln for ln in sec["intro"] if ln.startswith("**Summary")), "")
    if summary:
        para(doc, summary, 9.5)
    header, rows = table_from_lines(find_section(sec, "2."))
    if rows:
        col = {h: i for i, h in enumerate(header)}
        hit = [r for r in rows if float(r[col["Rows affected"]] or 0) > 0]
        para(doc, f"**Missing values and placeholders.** {len(hit)} of {len(rows)} checked columns contain placeholders; "
                  f"the other {len(rows) - len(hit)} are complete.", 9.5, space_after=3)
        add_table(doc, ["Column", "Rows (%)", "Treatment", "Why this is justified"],
                  [(f"{r[col['Table']]}.{r[col['Column']]}", f"{r[col['Rows affected']]} ({r[col['% of table']]}%)",
                    r[col["Treatment"]], r[col["Why this is justified"]]) for r in hit], widths=[1.5, 0.9, 1.2, 3.1], font=7.5)
    header, rows = table_from_lines(find_section(sec, "3."))
    if rows:
        add_table(doc, ["Integrity, duplicate and tie checks", "Result", "Status"], [(r[0], r[1], r[2]) for r in rows],
                  widths=[4.5, 0.9, 1.3], font=7.5)
    header, rows = table_from_lines(find_section(sec, "4."))
    if rows:
        failed = [r[0] for r in rows if r[-1] != "PASS"]
        para(doc, f"**Domain checks:** all {len(rows)} passed (rank at least 1, no negative points, valid week numbers, 3-letter country codes)."
                  if not failed else f"**Domain checks needing attention:** {', '.join(failed)}.", 9.5)
    header, rows = table_from_lines(find_section(sec, "5."))
    if rows:
        col = {h: i for i, h in enumerate(header)}
        add_table(doc, ["Ranking list", "Column", "Median", "Max", "Upper fence", "Above fence"],
                  [(r[col["Ranking list"]], r[col["Column"]], r[col["Median"]], r[col["Max"]], r[col["Upper fence"]], r[col["Above fence"]])
                   for r in rows], widths=[1.1, 1.6, 1.0, 1.0, 1.0, 1.0], font=7.5)
        para(doc, "Outliers are **kept**: very high points belong to the best players, who are the most important rows. "
                  "ATP and WTA points use different scales, so they are summarised per list.", 9.5)
    week = " ".join(ln for ln in find_section(sec, "6.") if ln.strip())
    if week:
        para(doc, "**Week-over-week validation.** " + week, 9.5)


def compact_explain(doc, md: str) -> None:
    sec = split_sections(md)
    header, rows = table_from_lines(find_section(sec, "Results"))
    if rows:
        add_table(doc, header, rows, widths=[0.4, 2.2, 0.9, 1.0, 1.2, 0.5, 0.5], font=7.5)
    bullets_ = [ln[2:] for ln in find_section(sec, "What the numbers say") if ln.startswith("- ")]
    for item in bullets_:
        bullet(doc, item)
    para(doc, "**Reading the plan:** type ALL is a full table scan; ref, range, const and eq_ref are index lookups. On small tables the "
              "optimizer may scan even when an index exists, and the index pays off as the data grows. Cases F and G have no index "
              "and show the full-scan baseline; cases H and I are JOINs that reach the second table through an index.", 9)


