# ------------------------------------------------------------------ word helpers
def shade(cell_or_par_pr, fill: str) -> None:
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), fill)
    cell_or_par_pr.append(shd)


def add_runs(paragraph, text: str, size: float | None = None, color: str | None = None, bold: bool = False) -> None:
    """Add text to a paragraph, turning **bold** and `code` into formatted runs."""
    for part in re.split(r"(\*\*.+?\*\*|`.+?`)", str(text)):
        if not part:
            continue
        if part.startswith("**") and part.endswith("**"):
            run, run.bold = paragraph.add_run(part[2:-2]), True
        elif part.startswith("`") and part.endswith("`"):
            run = paragraph.add_run(part[1:-1])
            run.font.name = "Consolas"
        else:
            run = paragraph.add_run(part)
            run.bold = bold or None
        if size:
            run.font.size = Pt(size)
        if color:
            run.font.color.rgb = RGBColor.from_string(color)


def para(doc, text: str, size: float | None = None, italic: bool = False, align=None, space_after: float = 6):
    p = doc.add_paragraph()
    add_runs(p, text, size)
    if italic:
        for run in p.runs:
            run.italic = True
    if align is not None:
        p.alignment = align
    p.paragraph_format.space_after = Pt(space_after)
    return p


def bullet(doc, text: str) -> None:
    p = doc.add_paragraph(style="List Bullet")
    add_runs(p, text)
    p.paragraph_format.space_after = Pt(2)


def heading(doc, text: str, level: int = 1) -> None:
    doc.add_heading(text.replace("`", ""), level=level)


def page_break(doc) -> None:
    doc.add_paragraph().add_run().add_break(WD_BREAK.PAGE)


def auto_widths(header: list, rows: list, total: float | None = None, font: float = 9, cap: int = 80) -> list:
    """Column widths (inches): each column gets room for its longest word, the rest is shared by text length."""
    total = total or TEXT_W
    char_w = font * 0.0078
    mins, weights = [], []
    for i, h in enumerate(header):
        cells = [str(h)] + [("" if r[i] is None else str(r[i])) for r in rows]
        longest_word = max((len(w) for c in cells for w in c.replace("/", "/ ").split()), default=1)
        mins.append(min(1.5, longest_word * char_w + 0.14))
        lengths = [min(len(c), cap) for c in cells]
        weights.append(max(0.6 * max(lengths) + 0.4 * sum(lengths) / len(lengths), 4))
    free = max(total - sum(mins), 0.0)
    widths = [m + free * w / sum(weights) for m, w in zip(mins, weights)]
    return [w * total / sum(widths) for w in widths]


def add_table(doc, header: list, rows: list, widths: list | None = None, font: float = 9) -> None:
    widths = widths or auto_widths(header, rows, font=font)
    table = doc.add_table(rows=1, cols=len(header))
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = False

    def fill(cell, text, bold=False, color=None, bg=None):
        cell.text = ""
        p = cell.paragraphs[0]
        p.paragraph_format.space_after = Pt(0)
        add_runs(p, "" if text is None else text, font, color, bold)
        if bg:
            shade(cell._tc.get_or_add_tcPr(), bg)

    for i, h in enumerate(header):
        fill(table.rows[0].cells[i], h, True, "FFFFFF", NAVY)
    trpr = table.rows[0]._tr.get_or_add_trPr()
    trpr.append(OxmlElement("w:tblHeader"))
    for n, row in enumerate(rows):
        cells = table.add_row().cells
        for i, value in enumerate(row):
            fill(cells[i], value, bg=GREY if n % 2 else None)
        table.rows[-1]._tr.get_or_add_trPr().append(OxmlElement("w:cantSplit"))
    for i, w in enumerate(widths):
        table.columns[i].width = Inches(w)
        for row in table.rows:
            row.cells[i].width = Inches(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(4)


def callout(doc, title: str, body: str, fill: str = "E0F2FE") -> None:
    table = doc.add_table(rows=1, cols=1)
    table.style = "Table Grid"
    cell = table.rows[0].cells[0]
    shade(cell._tc.get_or_add_tcPr(), fill)
    cell.text = ""
    p = cell.paragraphs[0]
    add_runs(p, title, 10.5, NAVY, True)
    p2 = cell.add_paragraph()
    add_runs(p2, body, 10)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)


def code_block(doc, text: str) -> None:
    p = doc.add_paragraph()
    shade(p._p.get_or_add_pPr(), GREY)
    p.paragraph_format.left_indent = Inches(0.1)
    lines = text.strip("\n").split("\n")
    for i, line in enumerate(lines):
        run = p.add_run(line)
        run.font.name, run.font.size = "Consolas", Pt(8)
        if i < len(lines) - 1:
            run.add_break()
    p.paragraph_format.space_after = Pt(6)


def figure(doc, path: Path | None, caption: str, max_w: float = 6.0, max_h: float = 7.0) -> None:
    if path is None or not Path(path).exists():
        MISSING.append(caption)
        para(doc, f"[Screenshot missing: {caption}]", 9, italic=True)
        return
    info = DocxImage.from_file(str(path))
    width = min(max_w, max_h * info.px_width / info.px_height)
    doc.add_picture(str(path), width=Inches(width))
    doc.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER
    doc.paragraphs[-1].paragraph_format.keep_with_next = True
    cap = para(doc, caption, 8.5, italic=True, align=WD_ALIGN_PARAGRAPH.CENTER, space_after=10)
    cap.paragraph_format.keep_together = True


def add_markdown(doc, text: str, base_level: int = 3) -> None:
    """Render the small Markdown subset produced by the report scripts (headings, tables, bullets, paragraphs)."""
    lines, i = text.splitlines(), 0
    while i < len(lines):
        line = lines[i].rstrip()
        if line.startswith("# ") or not line.strip():
            i += 1
        elif line.startswith("## "):
            heading(doc, line[3:].strip(), base_level)
            i += 1
        elif line.startswith("|"):
            block = []
            while i < len(lines) and lines[i].startswith("|"):
                block.append(lines[i])
                i += 1
            rows = [[c.strip().replace("\x00", "|") for c in r.replace("\\|", "\x00").strip().strip("|").split("|")]
                    for r in block if not re.match(r"^\|[\s\-:|]+\|$", r)]
            if rows:
                add_table(doc, rows[0], rows[1:], font=7.5 if len(rows[0]) > 5 else 8.5)
        elif line.startswith("- "):
            bullet(doc, line[2:])
            i += 1
        else:
            para(doc, line, 10)
            i += 1


def read_text(path: Path, label: str) -> str | None:
    if path.exists():
        return path.read_text(encoding="utf-8", errors="replace")
    MISSING.append(label)
    return None


