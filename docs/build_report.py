def collect_facts() -> dict:
    """Numbers for the insights and recommendations. Returns {} if the database cannot be reached."""
    try:
        from sqlalchemy import create_engine, text
        from api import config
        from db import data_quality as dq
        engine = create_engine(config.DB_URL, connect_args={**config.DB_CONNECT_ARGS, "connect_timeout": 10})

        def q(sql, params=None):
            with engine.connect() as conn:
                return pd.read_sql(text(sql), conn, params=params or {})

        facts = {"sizes": dq.table_sizes(engine).set_index("Table")["Rows"].to_dict(), "period": dq.latest_period(engine)}
        facts["venue_countries"] = q("SELECT country_name, COUNT(*) AS n FROM Venues GROUP BY country_name ORDER BY n DESC")
        facts["categories"] = q("SELECT cat.category_name, COUNT(*) AS n FROM Competitions c JOIN Categories cat "
                                "ON cat.category_id = c.category_id GROUP BY cat.category_name ORDER BY n DESC")
        facts["types"] = q("SELECT type, COUNT(*) AS n FROM Competitions GROUP BY type ORDER BY n DESC")
        facts["weeks"] = q("SELECT year, week, COUNT(*) AS n FROM Competitor_Rankings GROUP BY year, week ORDER BY year, week")
        if facts["period"]:
            y, w = facts["period"]
            facts["players"] = q("SELECT c.country, COUNT(DISTINCT c.competitor_id) AS n FROM Competitor_Rankings r "
                                 "JOIN Competitors c ON c.competitor_id = r.competitor_id WHERE r.year = :y AND r.week = :w "
                                 "GROUP BY c.country ORDER BY n DESC", {"y": y, "w": w})
            facts["stable_pct"] = float(q("SELECT 100.0 * SUM(CASE WHEN movement = 0 THEN 1 ELSE 0 END) / COUNT(*) AS p "
                                          "FROM Competitor_Rankings WHERE year = :y AND week = :w", {"y": y, "w": w}).iloc[0, 0])
        facts["movement"] = dq.movement_validation(engine)
        facts["engine"] = engine
        return facts
    except Exception as exc:  # noqa: BLE001 - the report must still build without a database
        print(f"[info] database not reachable, live numbers will be left generic: {type(exc).__name__}")
        return {}


def pct(part, whole) -> float:
    return 100.0 * part / whole if whole else 0.0


def top_share(df: pd.DataFrame | None, label_col: str, n: int = 1):
    """(label, count, percent of all) of the top row, plus the percent held by the top n rows."""
    if df is None or df.empty:
        return None
    total = df["n"].sum()
    top = df.iloc[0]
    return str(top[label_col]), int(top["n"]), pct(top["n"], total), pct(df.head(n)["n"].sum(), total), int(len(df))


