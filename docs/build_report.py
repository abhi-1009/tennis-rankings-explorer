def parse_pytest(text: str) -> tuple[list, str]:
    counts: dict = {}
    for line in text.splitlines():
        m = re.match(r"^tests/(\w+)\.py::.*\s(PASSED|FAILED|SKIPPED|ERROR)\s+\[\s*\d+%\]", line.strip())
        if m:
            counts.setdefault(m.group(1), {"PASSED": 0, "FAILED": 0, "SKIPPED": 0, "ERROR": 0})[m.group(2)] += 1
    rows = [(f"{name}.py", TEST_DESCRIPTIONS.get(name, ""), c["PASSED"], c["FAILED"] + c["ERROR"], c["SKIPPED"])
            for name, c in sorted(counts.items())]
    summary = re.search(r"=+\s*(.+?\bin [\d.]+s)\s*=+\s*$", text.strip().splitlines()[-1]) if text.strip() else None
    return rows, summary.group(1) if summary else ""


